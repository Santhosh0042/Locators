package assignmentoperators;

public class NewExamples {

	public static void main(String[] args) {
		
		int x = 50;
		int y = 10;
		
		x +=y;
		System.out.println("x +=y: +x");
		
		
		x -=y;
		System.out.println("x -=y: +x");
		
		x *=y;
		System.out.println("x *=y: +x");
		
		x /=y;
		System.out.println("x /=y: +x");
		
		x %=y;
		System.out.println("x %=y: +x");
		
	}
	}


