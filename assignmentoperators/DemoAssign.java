package assignmentoperators;

public class DemoAssign {

	
	
	public int Equalassign(int a , int b ) {
		return a=b;
	}
	public int addassign(int a , int b ) {
		return a+=b;
	}
	public int subassign(int a , int b ) {
		return a-=b;
	}
	public int multiassign(int a , int b ) {
		return a*=b;
	}
	public int divisionassign(int a , int b ) {
		return a/=b;
	}
	public int modulassign(int a , int b ) {
		return a%=b;
	}
}
